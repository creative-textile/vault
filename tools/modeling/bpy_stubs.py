#!/usr/bin/env python3
"""
bpy_stubs.py — creates empty stub libraries for X/GL libs that bpy wants but
the sandbox doesn't have (libXrender, libXi, libGL, ...).

The bpy wheel links X11/GL symbols. In a headless sandbox without them,
`import bpy` fails. We never render through those libs in mesh/GLTF mode,
so empty stubs that only satisfy the dynamic linker are enough. The stubs
export the union of ALL symbols the bpy shared libraries import
(anything GL-/X-family too), so versions/hooks like glXGetProcAddress
resolve as well.

Usage: bpy_stubs.py <bpy-package-dir> <out-dir>
Writes <out-dir>/USE if stubs were needed (wrap your python with
LD_LIBRARY_PATH=<out-dir>). Exit 0 if import works (with or without stubs),
1 if it cannot be made to work (no gcc to build stubs).
"""
import glob
import os
import re
import shutil
import subprocess
import sys

X_LIB_RE = re.compile(r"^(libX|libxkb|libSM|libICE|libGL|libGLX|libOpenGL|libEGL|libGLES|libVulkan|libOpenCL|libXrender|libXfixes|libXi|libglvnd)")


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout


def soname(p):
    m = re.search(r"(lib[^/]+\.so[.0-9]*)", p)
    return m.group(1) if m else os.path.basename(p)


def main():
    pkg, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)

    # 1. can we import without anything?
    if subprocess.run([sys.executable, "-c",
                       "import bpy, sys; sys.exit(0 if bpy.app.background else 1)"],
                      capture_output=True).returncode == 0:
        print("bpy imports fine, no stubs needed")
        return 0

    missing_libs = set()
    for so in glob.glob(os.path.join(pkg, "lib", "*.so*")) + [os.path.join(pkg, "__init__.so")]:
        if os.path.isfile(so):
            for line in run(["ldd", so]).splitlines():
                if "not found" in line:
                    missing_libs.add(soname(line.split()[0]))
    missing_libs = sorted(missing_libs)
    if not missing_libs:
        print("bpy imports fine, no stubs needed")
        return 0

    # 2. symbols to stub: everything the bpy libs import that nothing else provides
    undef = set()
    for so in glob.glob(os.path.join(pkg, "lib", "*.so*")) + [os.path.join(pkg, "__init__.so")]:
        if os.path.isfile(so):
            for line in run(["nm", "-D", "--undefined-only", so]).splitlines():
                parts = line.split()
                # format: "<spaces> U <symbol>" or "<spaces> w <symbol>";
                # line.split() eats the padding, so the marker is parts[0]
                if len(parts) >= 2 and parts[0] in ("U", "w", "v", "V"):
                    undef.add(parts[-1].split("@")[0])

    defined = set()
    for so in glob.glob(os.path.join(pkg, "lib", "*.so*")) + [os.path.join(pkg, "__init__.so")]:
        if os.path.isfile(so):
            for line in run(["nm", "-D", "--defined-only", so]).splitlines():
                parts = line.split()
                if len(parts) >= 3:
                    defined.add(parts[-1].split("@")[0])
    # symbols provided by any system library the bpy libs actually load + python itself
    for so in glob.glob(os.path.join(pkg, "lib", "*.so*")) + [os.path.join(pkg, "__init__.so")]:
        if os.path.isfile(so):
            for line in run(["ldd", so]).splitlines():
                if "=>" in line and "not found" not in line:
                    for lib in glob.glob(line.split("=>")[1].strip().split()[0] + "*"):
                        for l in run(["nm", "-D", "--defined-only", lib]).splitlines():
                            parts = l.split()
                            if len(parts) >= 3:
                                defined.add(parts[-1].split("@")[0])
    for l in glob.glob("/usr/lib/x86_64-linux-gnu/libpython3*.so*") + ["/usr/bin/python3"]:
        if os.path.isfile(l):
            for line in run(["nm", "-D", "--defined-only", l]).splitlines():
                parts = line.split()
                if len(parts) >= 3:
                    defined.add(parts[-1].split("@")[0])

    # always include GL/X-family symbols, whatever the scanner missed
    syms = sorted(s for s in (undef - defined) if s and not s.startswith("_Z"))
    syms += sorted(s for s in undef if X_LIB_RE.match(s) and s not in syms)
    # symbols that must never be stubbed (runtime machinery of loaded libs)
    skip = re.compile(r"^(_Z|__tls_get_addr|__cxa|__gxx|__register_atfork|__morestack|__asan_|__hip|__RML|__TBB_make|__TBB_call)")
    syms = [s for s in set(syms) if not skip.match(s)]
    if not syms:
        print("no symbols need stubbing")
        return 0

    # 3. generate and compile
    src = os.path.join(out, "stubs.c")
    with open(src, "w") as f:
        f.write("/* auto-generated by bpy_stubs.py — DO NOT EDIT */\n")
        for s in syms:
            f.write(f"void {s}(void) {{}}\n")
    if shutil.which("gcc") is None:
        print("ERROR: bpy needs X/GL libs that this system lacks, and gcc is missing "
              "to build stubs. Install the libs, e.g.:", file=sys.stderr)
        print("  apt-get install libxrender1 libxfixes3 libxi6 libxkbcommon0 libsm6 libice6 libgl1 libglx0 libegl1 libopengl0", file=sys.stderr)
        return 1
    libs_dir = out  # LD_LIBRARY_PATH points here directly
    sonames_needed = set(missing_libs)
    # one .so per missing lib, all symbols exported from each
    compiled = []
    for lib in sorted(sonames_needed):
        so = os.path.join(out, lib)
        subprocess.run(["gcc", "-shared", "-fPIC", "-o", so, "-Wl,-soname," + lib, src], check=True)
        compiled.append(lib)
    # plus one plain libGL.so.1 (some libs dlopen it by name)
    if "libGL.so.1" not in compiled:
        subprocess.run(["gcc", "-shared", "-fPIC", "-o", os.path.join(libs_dir, "libGL.so.1"),
                        "-Wl,-soname,libGL.so.1", src], check=True)
    open(os.path.join(out, "USE"), "w").write("1\n")
    print(f"built stubs in {libs_dir} for: {', '.join(sorted(sonames_needed) + ['libGL.so.1'])} ({len(syms)} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

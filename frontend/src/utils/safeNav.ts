import type { NavigateFunction } from 'react-router-dom';

/**
 * Переход на экран итогов сейфа так, чтобы «назад» всегда вёл в главное меню.
 *
 * Раньше выдёргивание во взлом делалось через `push`, и история выглядела как
 * [/duel, /safe/crack] или [/safe, /safe/crack]. После розыгрыша игрок попадал
 * на /safe, и кнопка «назад» возвращала его туда, откуда забрали: из /safe —
 * снова в /safe (нажимать дважды), из /duel — в /duel. По требованию эта фича
 * убрана: с экрана сейфа «назад» всегда ведёт в главное меню.
 *
 * Поэтому текущая запись истории (/safe/crack) сначала заменяется на главную,
 * а уже поверх неё кладётся /safe. В итоге под экраном итогов всегда лежит '/',
 * и работает это и для браузерного «назад», и для системного жеста в Telegram.
 */
export function goToSafeResults(nav: NavigateFunction) {
  nav('/', { replace: true });
  nav('/safe');
}
